import { describe, expect, it } from 'vitest'
import { shortVariantNames } from '@/lib/variantName'

describe('shortVariantNames', () => {
  it('убирает общее название серии, бренд и габариты', () => {
    expect(
      shortVariantNames(
        [
          { name: 'Бокал для вина «Трибьют Коллекшн» хр.стекло 340мл D=8,H=17см прозр.' },
          { name: 'Олд фэшн (стакан) «Трибьют Коллекшн» хр.стекло 285мл D=75,H=75мм прозр.' },
        ],
        'RONA'
      )
    ).toEqual(['Бокал для вина хр.стекло 340мл прозр.', 'Олд фэшн (стакан) хр.стекло 285мл прозр.'])
  })

  it('оставляет название в кавычках, если оно у вариантов разное (вкусы)', () => {
    expect(
      shortVariantNames(
        [{ name: 'Сироп «Пандан» ODK стекло 0,75л D=65,H=305мм' }, { name: 'Сироп «Агава» ODK стекло 0,75л D=65,H=305мм' }],
        'ODK'
      )
    ).toEqual(['Сироп «Пандан» стекло 0,75л', 'Сироп «Агава» стекло 0,75л'])
  })

  it('варианты без названия (добавленные раньше) дают пустую строку', () => {
    expect(shortVariantNames([{}, { name: '' }], 'RONA')).toEqual(['', ''])
  })
})
